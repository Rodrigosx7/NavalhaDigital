-- Run once using the operator connection, never from an HTTP cold start.
CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA extensions;
CREATE SCHEMA IF NOT EXISTS navalha;
SET LOCAL search_path = navalha, extensions, pg_catalog;

CREATE TABLE navalha.configuracao(chave text PRIMARY KEY, valor text NOT NULL);
CREATE TABLE navalha.usuarios(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  perfil text NOT NULL CHECK(perfil IN ('CLIENTE','BARBEIRO')),
  email_indice text NOT NULL UNIQUE, dados text NOT NULL, senha_hash text NOT NULL,
  data_cadastro timestamp(0) NOT NULL
);
CREATE TABLE navalha.sessoes(token_hash text PRIMARY KEY, usuario_id integer NOT NULL REFERENCES navalha.usuarios(id), csrf text NOT NULL, expira bigint NOT NULL);
CREATE TABLE navalha.convites(email_indice text NOT NULL, segredo_hash text PRIMARY KEY, expira bigint NOT NULL, utilizado integer NOT NULL DEFAULT 0 CHECK(utilizado IN (0,1)));
CREATE TABLE navalha.servicos(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL, descricao text NOT NULL,
  categoria text NOT NULL CHECK(categoria IN ('CORTE','BARBA','TRATAMENTO','OUTRO')),
  preco_centavos integer NOT NULL CHECK(preco_centavos BETWEEN 0 AND 100000000),
  duracao integer NOT NULL CHECK(duracao BETWEEN 1 AND 1440), ativo integer NOT NULL CHECK(ativo IN (0,1))
);
CREATE TABLE navalha.disponibilidades(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barbeiro_id integer NOT NULL REFERENCES navalha.usuarios(id),
  dia text NOT NULL CHECK(dia IN ('DOMINGO','SEGUNDA','TERCA','QUARTA','QUINTA','SEXTA','SABADO')),
  inicio text NOT NULL, fim text NOT NULL, intervalo integer NOT NULL CHECK(intervalo BETWEEN 1 AND 1440),
  ativo integer NOT NULL CHECK(ativo IN (0,1))
);
CREATE TABLE navalha.agendamentos(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id integer NOT NULL REFERENCES navalha.usuarios(id), barbeiro_id integer NOT NULL REFERENCES navalha.usuarios(id),
  disponibilidade_id integer NOT NULL REFERENCES navalha.disponibilidades(id), data_hora timestamp(0) NOT NULL,
  status text NOT NULL CHECK(status IN ('PENDENTE','CONCLUIDO','NAO_COMPARECEU','CANCELADO')),
  observacao text NOT NULL, data_criacao timestamp(0) NOT NULL, data_atualizacao timestamp(0) NOT NULL,
  valor_centavos integer NOT NULL CHECK(valor_centavos>=0), duracao integer NOT NULL CHECK(duracao>0), itens text NOT NULL,
  periodo tsrange GENERATED ALWAYS AS (tsrange(data_hora, data_hora + duracao * interval '1 minute', '[)')) STORED,
  CONSTRAINT sem_sobreposicao EXCLUDE USING gist (barbeiro_id WITH =, periodo WITH &&) WHERE (status <> 'CANCELADO')
);
CREATE INDEX reservas_barbeiro_data ON navalha.agendamentos(barbeiro_id,data_hora);
CREATE INDEX reservas_cliente ON navalha.agendamentos(cliente_id,data_hora);
CREATE INDEX janelas_barbeiro ON navalha.disponibilidades(barbeiro_id,dia);
CREATE INDEX sessoes_expiracao ON navalha.sessoes(expira);
CREATE TABLE navalha.operacoes(chave text PRIMARY KEY, usuario_id integer NOT NULL REFERENCES navalha.usuarios(id), agendamento_id integer NOT NULL REFERENCES navalha.agendamentos(id), assinatura text NOT NULL);
CREATE TABLE navalha.tentativas(chave text PRIMARY KEY, quantidade integer NOT NULL, expira bigint NOT NULL);

